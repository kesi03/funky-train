#!/usr/bin/env python3
"""vforge.py -- build Vibe FM data and readable specs from a .vforge patch source.

    python tools/vforge.py build-c   patches/funk-masters-a.vforge.json \
        firmware/funky-train/patches.generated.h
    python tools/vforge.py spec      patches/funk-masters-a.vforge.json BANK-A.md
    python tools/vforge.py dx7-check patches/funk-masters-a.vforge.json DX7-MISSING.md

The DX7 side is deliberately *not* a SysEx generator. A DX7 voice needs every
operator's envelopes, levels, keyboard scaling, detune and rate data (155 bytes).
The bank here is a high-level design spec: dx7-check reports exactly what is
missing. When a patch has dx7.complete = true and all six operators are fully
specified, a real .syx encoder can be added without changing the source format.
"""
import json
import sys
from pathlib import Path

FX_IDS = {
    "chorus": "P_CHORUS", "drive": "P_DRIVE", "delay_mix": "P_DELAY_MIX",
    "reverb_mix": "P_REVERB_MIX", "wah_mode": "P_WAH_MODE", "wah_mix": "P_WAH_MIX",
    "wah_res": "P_WAH_RES", "dimension": "P_DIM", "phaser": "P_PHASER",
    "rotary": "P_ROTARY", "rot_speed": "P_ROT_SPEED", "rot_mix": "P_ROT_MIX",
    "vib_depth": "P_VIB_DEPTH", "comp": "P_COMP", "sat_type": "P_SAT_TYPE",
}
MAX_PFX = 5


def load(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if data.get("format") != "vforge/1":
        raise SystemExit("unsupported .vforge format")
    patches = data.get("patches") or []
    if not patches:
        raise SystemExit("no patches in source")
    ids = [p["id"] for p in patches]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate patch id in source")
    return data, patches


def sec(ms):
    return float(ms) / 1000.0


def env(p, key):
    a = p.get(key) or [1, 100, 0, 50]
    while len(a) < 4:
        a.append(0)
    return a[0] / 1000.0, sec(a[1]), a[2] / 100.0, sec(a[3])


def cfloat(v):
    s = f"{float(v):.6f}".rstrip("0").rstrip(".")
    return s if s else "0"


def patch_init(p):
    v = p["vibe_fm"]
    kind = v.get("kind", "fm")
    name = p["name"].replace('"', '\\"')
    if kind == "fm":
        ma, md, ms, mr = env(v, "m")
        ca, cd, cs, cr = env(v, "c")
        return (f'  {{ "{name}", FT_KIND_FM, .ratio={cfloat(v["ratio"])}, '
                f'.index={cfloat(v["index"])}, .fb={cfloat(v["fb"])}, '
                f'.m_ar={cfloat(ma)}, .m_dr={cfloat(md)}, .m_sl={cfloat(ms)}, .m_rr={cfloat(mr)}, '
                f'.c_ar={cfloat(ca)}, .c_dr={cfloat(cd)}, .c_sl={cfloat(cs)}, .c_rr={cfloat(cr)}, '
                f'.level={cfloat(v["level"])}, .octave={int(v.get("octave", 0))} }}')
    if kind == "va":
        aa, ad, as_, ar = env(v, "amp") if v.get("amp") else (0.01, 0.65, 0.82, 0.35)
        return (f'  {{ "{name}", FT_KIND_VA, .wave1={int(v["w1"])}, .wave2={int(v["w2"])}, '
                f'.sub={int(v["sub"])}, .detune={cfloat(v["detune"])}, '
                f'.cutoff={cfloat(v["cutoff"])}, .res={cfloat(v["res"])}, '
                f'.fenv={cfloat(v["fenv"])}, .fdec={cfloat(sec(v["fdec"]))}, '
                f'.fattack={cfloat(sec(v["fattack"]))}, '
                f'.c_ar={cfloat(aa)}, .c_dr={cfloat(ad)}, .c_sl={cfloat(as_)}, .c_rr={cfloat(ar)}, '
                f'.level={cfloat(v["level"])}, .octave={int(v.get("octave", 0))} }}')
    if kind == "organ":
        d = v["draw"]
        da = ", ".join(cfloat(x) for x in d)
        aa, ad, as_, ar = env(v, "amp") if v.get("amp") else (0.005, 0.15, 0.95, 0.15)
        return (f'  {{ "{name}", FT_KIND_ORGAN, .draw={{ {da} }}, '
                f'.c_ar={cfloat(aa)}, .c_dr={cfloat(ad)}, .c_sl={cfloat(as_)}, .c_rr={cfloat(ar)}, '
                f'.level={cfloat(v["level"])}, .octave={int(v.get("octave", 0))} }}')
    raise SystemExit(f'unknown engine kind {kind!r} in {p["id"]}')


def build_c(data, patches, out):
    n = len(patches)
    lines = [
        "/* GENERATED by tools/vforge.py from patches/funk-masters-a.vforge.json.",
        " * Do not edit by hand. Regenerate after changing the .vforge source. */",
        "#ifndef FT_PATCHES_GENERATED_H",
        "#define FT_PATCHES_GENERATED_H",
        "",
        f"#define FT_PATCH_COUNT {n}",
        "",
        "static const ft_patch FT_PATCHES[FT_PATCH_COUNT] = {",
    ]
    for p in patches:
        lines.append(f"  /* {p['id']} -- {p.get('type', '')} */")
        lines.append(patch_init(p) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const char *const FT_PATCH_NAMES[FT_PATCH_COUNT] = {")
    lines.append(", ".join('"' + p["name"].replace('"', '\\"') + '"' for p in patches))
    lines.append("};")
    lines.append("")
    lines.append("#ifdef FT_GENERATE_FX_OVERRIDES")
    lines.append(f"#define FT_PFX_MAX {MAX_PFX}")
    lines.append("static const int FT_PFX_ID[FT_PFX_MAX][FT_PATCH_COUNT] = {")
    for i in range(MAX_PFX):
        row = []
        for p in patches:
            fx = (p.get("vibe_fm") or {}).get("fx") or []
            if i < len(fx):
                key = fx[i][0]
                row.append(FX_IDS.get(key, "-1") if key in FX_IDS else "-1")
            else:
                row.append("-1")
        lines.append("  { " + ", ".join(row) + " },")
    lines.append("};")
    lines.append("static const float FT_PFX_VAL[FT_PFX_MAX][FT_PATCH_COUNT] = {")
    for i in range(MAX_PFX):
        row = []
        for p in patches:
            fx = (p.get("vibe_fm") or {}).get("fx") or []
            row.append(cfloat(fx[i][1]) if i < len(fx) and fx[i][0] in FX_IDS else "0")
        lines.append("  { " + ", ".join(row) + " },")
    lines.append("};")
    lines.append("#endif /* FT_GENERATE_FX_OVERRIDES */")
    lines.append("")
    lines.append("#endif")
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}: {n} patches")


def build_spec(data, patches, out):
    lines = [f"# {data['bank']}", "", data.get("description", ""), "",
             "These are design specifications for a common `.vforge` source. They are not raw DX7 SysEx.",
             "", "| # | Voice | Type | Algorithm | Ratios | Character | Engine (Vibe FM) |",
             "|---|-------|------|-----------|--------|-----------|------------------|"]
    for i, p in enumerate(patches, 1):
        ratios = ", ".join(str(r) for r in p.get("ratios", [])) or "-"
        char = p.get("character", p.get("type", ""))
        line = "| %02d | %s | %s | %s | %s | %s | %s |" % (
            i, p["name"], p.get("type", "-"), p.get("algorithm", "-"),
            ratios, char, p.get("vibe_fm", {}).get("kind", "-"))
        lines.append(line)
    lines += ["", "## Detailed specifications", ""]
    for i, p in enumerate(patches, 1):
        lines += [f"### {i:02d} {p['name']}", "",
                  f"- Type: {p.get('type', '-')}",
                  f"- Algorithm: {p.get('algorithm', '-')}",
                  f"- Feedback: {p.get('feedback', '-')}",
                  f"- Ratios: {', '.join(str(r) for r in p.get('ratios', [])) or '-'}",
                  f"- Character: {p.get('character', '-')}"]
        if p.get("levels"):
            lines.append(f"- Operator levels: {', '.join(str(v) for v in p['levels'])}")
        if p.get("lfo"):
            lfo = p["lfo"]
            lines.append(f"- LFO: {lfo.get('wave', '-')}, speed {lfo.get('speed', '-')}, delay {lfo.get('delay', 0)}")
        if p.get("mono"):
            lines.append(f"- Mono: on, portamento {p.get('portamento', 0)}")
        lines.append("- DX7 SysEx: not available from this high-level spec; requires all 6 operator envelopes, levels, scaling and detune.")
        lines.append("")
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


def dx7_check(data, patches, out):
    lines = ["# DX7 completeness report", "",
             "No `.syx` was generated. High-level voice descriptions cannot be converted into",
             "a genuine DX7 voice dump: the 155-byte voice block needs six complete operator",
             "records (rates, levels, keyboard scaling, detune, waveform, velocity sensitivity),",
             "plus pitch envelope and LFO data. Fill these fields in the `.vforge` source and",
             "set `dx7.complete = true` to enable a real SysEx encoder.", "",
             "| Voice | Complete | Missing |", "|-------|----------|---------|"]
    for p in patches:
        d = p.get("dx7") or {}
        miss = ", ".join(d.get("missing") or []) or "-"
        lines.append("| %s | %s | %s |" % (
            p["name"], "yes" if d.get("complete") else "no", miss))
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    complete = sum(1 for p in patches if (p.get("dx7") or {}).get("complete"))
    print(f"DX7 SysEx intentionally not generated: {complete}/{len(patches)} voices are fully specified")
    print(f"wrote {out}")


def main():
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    cmd, src, out = sys.argv[1], sys.argv[2], sys.argv[3]
    data, patches = load(src)
    if cmd == "build-c":
        build_c(data, patches, out)
    elif cmd == "spec":
        build_spec(data, patches, out)
    elif cmd == "dx7-check":
        dx7_check(data, patches, out)
    else:
        raise SystemExit(f"unknown command {cmd!r}")


if __name__ == "__main__":
    main()
